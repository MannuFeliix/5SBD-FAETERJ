    nome_dependente VARCHAR2(80),
    grau_parentesco VARCHAR2(30),
    data_nascimento DATE
);
/

-- 3. Criação da Nested Table baseada no objeto t_dependente
CREATE OR REPLACE TYPE t_dependentes_nested AS TABLE OF t_dependente;
/

