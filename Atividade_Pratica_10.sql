-- Exercício 2: Método MAP para Ordenação em t_retangulo
CREATE OR REPLACE TYPE t_retangulo AS OBJECT (
    largura NUMBER,
    altura  NUMBER,
    MEMBER FUNCTION calcular_area RETURN NUMBER,
    MEMBER FUNCTION calcular_perimetro RETURN NUMBER,
    MAP MEMBER FUNCTION ordenar RETURN NUMBER
);
/

CREATE OR REPLACE TYPE BODY t_retangulo AS
    MEMBER FUNCTION calcular_area RETURN NUMBER IS
    BEGIN
        RETURN largura * altura;
    END;

    MEMBER FUNCTION calcular_perimetro RETURN NUMBER IS
    BEGIN
        RETURN 2 * (largura + altura);
    END;

    MAP MEMBER FUNCTION ordenar RETURN NUMBER IS
    BEGIN
        RETURN largura * altura;
    END;
END;
/

-- Tabela de teste e ordenação direta pela coluna do tipo objeto
CREATE TABLE tb_retangulos (
    id_retangulo NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao    VARCHAR2(50),
    forma        t_retangulo
);

INSERT INTO tb_retangulos (descricao, forma) VALUES ('Retângulo Grande', t_retangulo(10, 8));
INSERT INTO tb_retangulos (descricao, forma) VALUES ('Retângulo Pequeno', t_retangulo(3, 4));
INSERT INTO tb_retangulos (descricao, forma) VALUES ('Retângulo Médio', t_retangulo(5, 6));
COMMIT;

SELECT
    r.id_retangulo,
    r.descricao,
    r.forma.largura AS largura,
    r.forma.altura AS altura,
    r.forma.calcular_area() AS area
FROM tb_retangulos r
ORDER BY r.forma ASC;

