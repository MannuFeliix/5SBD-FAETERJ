    logradouro VARCHAR2(100),
    numero     VARCHAR2(10),
    bairro     VARCHAR2(50),
    cidade     VARCHAR2(50),
    uf         VARCHAR2(2),
    cep        VARCHAR2(9),
    MEMBER FUNCTION get_endereco_completo RETURN VARCHAR2
