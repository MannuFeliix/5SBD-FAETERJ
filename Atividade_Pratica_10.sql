CREATE OR REPLACE TYPE BODY t_endereco AS
    MEMBER FUNCTION get_endereco_completo RETURN VARCHAR2 IS
    BEGIN
        RETURN logradouro || ', ' || numero || ' - ' || bairro || ', ' ||
               cidade || '/' || uf || ' (CEP: ' || cep || ')';
    END;
END;
