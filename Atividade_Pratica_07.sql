-- Exercício 1: Materialized View mv_vendas_categoria (REFRESH COMPLETE ON DEMAND)
CREATE MATERIALIZED VIEW mv_vendas_categoria
BUILD IMMEDIATE
REFRESH COMPLETE ON DEMAND
AS
SELECT
    p.categoria,
    COUNT(v.id_venda) AS qtd_vendas,
    SUM(v.quantidade) AS qtd_itens_vendidos,
    SUM(v.valor_total) AS faturamento_total
FROM tb_vendas v
JOIN tb_produtos p ON v.id_produto = p.id_produto
GROUP BY p.categoria;

SELECT * FROM mv_vendas_categoria ORDER BY faturamento_total DESC;

/*
  SIMULAÇÃO DE RESULTADO (EXERCÍCIO 1):
  Materialized view MV_VENDAS_CATEGORIA created.

