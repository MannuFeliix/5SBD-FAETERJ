-- ==========================================================
-- ETAPA 2: Criação do Materialized View Log (Fast Refresh)
-- ==========================================================

CREATE MATERIALIZED VIEW LOG ON tb_vendas
WITH ROWID, SEQUENCE (id_produto, quantidade, valor_total)
INCLUDING NEW VALUES;

/*
  SIMULAÇÃO DE RESULTADO (ETAPA 2):
  Materialized view log created.
*/


-- ==========================================================
-- ETAPA 3: Criação da Materialized View com Agregação
-- ==========================================================

CREATE MATERIALIZED VIEW mv_vendas_por_produto
BUILD IMMEDIATE
REFRESH FAST ON DEMAND
ENABLE QUERY REWRITE
AS
SELECT
    v.id_produto,
    COUNT(*) AS total_transacoes,
    SUM(v.quantidade) AS qtd_total_vendida,
    SUM(v.valor_total) AS faturamento_total,
    COUNT(v.valor_total) AS count_faturamento
FROM tb_vendas v
GROUP BY v.id_produto;

/*
  SIMULAÇÃO DE RESULTADO (ETAPA 3):
  Materialized view MV_VENDAS_POR_PRODUTO created.

  Nota: COUNT(*) e COUNT(v.valor_total) suportam FAST REFRESH em agregações
  permitindo ajustes incrementais quando ocorrem inserções, alterações ou exclusões[cite: 17].
*/


-- ==========================================================
-- ETAPA 4: Consulta e Validação Inicial
-- ==========================================================

SELECT
    p.nome_produto,
    p.categoria,
    mv.total_transacoes,
    mv.qtd_total_vendida,
    mv.faturamento_total
FROM mv_vendas_por_produto mv
JOIN tb_produtos p ON p.id_produto = mv.id_produto
ORDER BY mv.faturamento_total DESC;

