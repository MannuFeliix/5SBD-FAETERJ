-- 1. Relatório consolidado de remuneração bruta, comissão e desconto de IRRF[cite: 67]
SELECT
    c.id_colaborador,
    c.nome,
    c.departamento,
    c.salario_base,
    fnc_obter_comissao(c.id_colaborador, '10/2026') AS comissao_outubro,
    (c.salario_base + fnc_obter_comissao(c.id_colaborador, '10/2026')) AS remuneracao_bruta,
    fnc_calcular_irrf(c.salario_base + fnc_obter_comissao(c.id_colaborador, '10/2026')) AS desconto_irrf,
    (c.salario_base + fnc_obter_comissao(c.id_colaborador, '10/2026')) -
    fnc_calcular_irrf(c.salario_base + fnc_obter_comissao(c.id_colaborador, '10/2026')) AS salario_liquido_estimado
FROM tb_colaboradores c
ORDER BY remuneracao_bruta DESC;

-- 2. Uso da função dentro da cláusula WHERE para filtragem de faixa[cite: 67]
SELECT nome, salario_base
FROM tb_colaboradores
WHERE fnc_calcular_irrf(salario_base) > 300.00;

