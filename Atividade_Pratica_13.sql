CREATE OR REPLACE FUNCTION fnc_calcular_irrf (
    p_salario_bruto IN NUMBER
) RETURN NUMBER
DETERMINISTIC
IS
    v_imposto NUMBER(10,2) := 0;
BEGIN
    IF p_salario_bruto IS NULL OR p_salario_bruto <= 2259.20 THEN
        v_imposto := 0;
    ELSIF p_salario_bruto <= 2826.65 THEN
        v_imposto := (p_salario_bruto * 0.075) - 169.44;
    ELSIF p_salario_bruto <= 3751.05 THEN
        v_imposto := (p_salario_bruto * 0.15) - 381.44;
    ELSIF p_salario_bruto <= 4664.68 THEN
        v_imposto := (p_salario_bruto * 0.225) - 662.77;
    ELSE
        v_imposto := (p_salario_bruto * 0.275) - 896.00;
    END IF;

    RETURN ROUND(GREATEST(v_imposto, 0), 2);
EXCEPTION
    WHEN OTHERS THEN
        RETURN 0;
END fnc_calcular_irrf;
