CREATE OR REPLACE FUNCTION fnc_obter_comissao (
    p_id_colaborador IN NUMBER,
    p_mes_ano        IN VARCHAR2
) RETURN NUMBER IS
    v_total_vendas NUMBER(12,2) := 0;
    v_percentual   NUMBER(5,4)  := 0;
BEGIN
    SELECT NVL(SUM(total_vendido), 0)
    INTO v_total_vendas
    FROM tb_vendas_colaborador
    WHERE id_colaborador = p_id_colaborador
      AND mes_ano = p_mes_ano;

    IF v_total_vendas >= 100000.00 THEN
        v_percentual := 0.05;
    ELSIF v_total_vendas >= 50000.00 THEN
        v_percentual := 0.035;
    ELSIF v_total_vendas > 0 THEN
        v_percentual := 0.02;
    ELSE
        v_percentual := 0;
    END IF;

    RETURN ROUND(v_total_vendas * v_percentual, 2);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 0;
    WHEN OTHERS THEN
        RETURN 0;
END fnc_obter_comissao;
