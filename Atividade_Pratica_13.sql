-- Exercício 2: Violação de Pureza e Erro ORA-14551[cite: 68, 69]
CREATE OR REPLACE FUNCTION fnc_teste_dml
RETURN NUMBER IS
BEGIN
    UPDATE tb_colaboradores
    SET salario_base = salario_base
    WHERE id_colaborador = 1;

    RETURN 1;
END fnc_teste_dml;
/

-- Tentativa de execução dentro de uma instrução SELECT:
SELECT fnc_teste_dml() FROM DUAL;

/*
  SIMULAÇÃO DE RESULTADO / ERRO ESPERADO (EXERCÍCIO 2):
  Function FNC_TESTE_DML compiled.
  ORA-14551: cannot perform a DML operation inside a query[cite: 69]

  Análise: Uma consulta SELECT tem contexto somente leitura. Ao invocar uma
  função que tenta executar INSERT/UPDATE/DELETE sem pragma autônomo, o Oracle
  bloqueia a execução para preservar o nível de pureza e a consistência da leitura[cite: 62, 68, 69].
*/


