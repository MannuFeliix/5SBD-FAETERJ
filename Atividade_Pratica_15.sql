-- Exercício 1: Trigger INSTEAD OF em View com JOIN
CREATE OR REPLACE VIEW vw_empregados_resumo AS
SELECT e.id_empregado,
       e.nome,
       e.cargo,
       e.salario,
       e.status,
       COUNT(a.id_audit) AS qtd_auditorias
FROM tb_empregados e
LEFT JOIN tb_auditoria_salarios a ON a.id_empregado = e.id_empregado
GROUP BY e.id_empregado, e.nome, e.cargo, e.salario, e.status;

CREATE OR REPLACE TRIGGER trg_vw_empregados_io_insert
INSTEAD OF INSERT ON vw_empregados_resumo
FOR EACH ROW
BEGIN
    INSERT INTO tb_empregados (nome, cargo, salario, status)
    VALUES (:NEW.nome, :NEW.cargo, :NEW.salario, NVL(:NEW.status, 'ATIVO'));
END trg_vw_empregados_io_insert;
/

