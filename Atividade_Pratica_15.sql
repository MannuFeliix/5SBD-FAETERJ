-- Exercício 3: Cláusula WHEN no gatilho de auditoria
CREATE OR REPLACE TRIGGER trg_empregados_auditoria
AFTER INSERT OR UPDATE OF salario OR DELETE ON tb_empregados
FOR EACH ROW
WHEN (
    (TG_OP = 'INSERT')
    OR (TG_OP = 'UPDATE' AND NVL(NEW.salario, -1) <> NVL(OLD.salario, -1))
    OR (TG_OP = 'DELETE')
)
BEGIN
    IF INSERTING THEN
        INSERT INTO tb_auditoria_salarios (id_empregado, operacao, salario_anterior, salario_novo)
        VALUES (:NEW.id_empregado, 'INSERT', NULL, :NEW.salario);
    ELSIF UPDATING THEN
        INSERT INTO tb_auditoria_salarios (id_empregado, operacao, salario_anterior, salario_novo)
        VALUES (:OLD.id_empregado, 'UPDATE', :OLD.salario, :NEW.salario);
    ELSIF DELETING THEN
        INSERT INTO tb_auditoria_salarios (id_empregado, operacao, salario_anterior, salario_novo)
        VALUES (:OLD.id_empregado, 'DELETE', :OLD.salario, NULL);
    END IF;
END trg_empregados_auditoria;
/

/*
  RESULTADO (EXERCÍCIO 3):
  Trigger TRG_EMPREGADOS_AUDITORIA compiled.
  - A cláusula WHEN avalia a condição antes de entrar no corpo PL/SQL,
    evitando chamadas desnecessárias ao motor PL/SQL quando o salário não muda.
*/
