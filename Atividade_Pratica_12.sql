-- Exercício 1: Procedure de Reajuste em Massa (IN e OUT)[cite: 59]
CREATE OR REPLACE PROCEDURE prc_reajustar_saldo_em_massa (
    p_percentual       IN  NUMBER,
    p_total_atualizado OUT NUMBER
) IS
BEGIN
    UPDATE tb_contas
    SET saldo = saldo * (1 + (p_percentual / 100))
    WHERE status = 'ATIVA';

    p_total_atualizado := SQL%ROWCOUNT;
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        p_total_atualizado := 0;
        ROLLBACK;
        RAISE;
END prc_reajustar_saldo_em_massa;
/

-- Bloco de teste para o Exercício 1 (reajuste de 10% nas contas ativas):
DECLARE
    v_qtd_contas NUMBER;
BEGIN
    prc_reajustar_saldo_em_massa(
        p_percentual       => 10,
        p_total_atualizado => v_qtd_contas
    );
    DBMS_OUTPUT.PUT_LINE('Total de contas ativas reajustadas: ' || v_qtd_contas);
END;
/

