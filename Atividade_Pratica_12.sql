CREATE OR REPLACE PROCEDURE prc_transferir_fundos (
    p_origem  IN NUMBER,
    p_destino IN NUMBER,
    p_valor   IN NUMBER
) IS
    v_saldo_origem       NUMBER;
    v_status_orig        VARCHAR2(10);
    v_status_dest        VARCHAR2(10);
    e_saldo_insuficiente EXCEPTION;
    e_conta_bloqueada    EXCEPTION;
BEGIN
    IF p_valor <= 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Valor de transferência inválido.');
    END IF;[cite: 56]

    SELECT saldo, status INTO v_saldo_origem, v_status_orig
    FROM tb_contas
    WHERE id_conta = p_origem
    FOR UPDATE;[cite: 56]

    IF v_status_orig <> 'ATIVA' THEN
        RAISE e_conta_bloqueada;
    END IF;[cite: 56]

    IF v_saldo_origem < p_valor THEN
        RAISE e_saldo_insuficiente;
    END IF;[cite: 56, 57]

    SELECT status INTO v_status_dest
    FROM tb_contas
    WHERE id_conta = p_destino;[cite: 57]

    IF v_status_dest <> 'ATIVA' THEN
        RAISE e_conta_bloqueada;
    END IF;[cite: 57]

    UPDATE tb_contas SET saldo = saldo - p_valor WHERE id_conta = p_origem;[cite: 57]
    UPDATE tb_contas SET saldo = saldo + p_valor WHERE id_conta = p_destino;[cite: 57]

    INSERT INTO tb_movimentacoes (id_conta_origem, id_conta_dest, tipo_operacao, valor)
    VALUES (p_origem, p_destino, 'TRANSFERENCIA', p_valor);[cite: 57]

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Transferência de R$ ' || p_valor || ' concluída com sucesso.');[cite: 57]
EXCEPTION
    WHEN e_saldo_insuficiente THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20002, 'Falha: Saldo insuficiente na conta de origem.');[cite: 57]
    WHEN e_conta_bloqueada THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20003, 'Falha: Uma das contas envolvidas está bloqueada.');[cite: 57]
    WHEN NO_DATA_FOUND THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20004, 'Falha: Conta de origem ou destino não localizada.');[cite: 57]
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20099, 'Erro inesperado na transferência: ' || SQLERRM);[cite: 57, 58]
END prc_transferir_fundos;
