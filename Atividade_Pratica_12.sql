CREATE OR REPLACE PROCEDURE prc_realizar_deposito (
    p_id_conta   IN  NUMBER,
    p_valor      IN  NUMBER,
    p_novo_saldo OUT NUMBER,
    p_status_msg OUT VARCHAR2
) IS
    v_status_conta VARCHAR2(10);
BEGIN
    IF p_valor <= 0 THEN
        p_status_msg := 'ERRO: O valor do depósito deve ser maior que zero.';
        p_novo_saldo := NULL;
        RETURN;
    END IF;[cite: 54]

    SELECT status, saldo INTO v_status_conta, p_novo_saldo
    FROM tb_contas
    WHERE id_conta = p_id_conta;[cite: 54]

    IF v_status_conta <> 'ATIVA' THEN
        p_status_msg := 'ERRO: A conta está bloqueada ou inativa.';
        p_novo_saldo := NULL;
        RETURN;
    END IF;[cite: 54]

    UPDATE tb_contas
    SET saldo = saldo + p_valor
    WHERE id_conta = p_id_conta
    RETURNING saldo INTO p_novo_saldo;[cite: 54, 55]

    INSERT INTO tb_movimentacoes (id_conta_dest, tipo_operacao, valor)
    VALUES (p_id_conta, 'DEPOSITO', p_valor);[cite: 55]

    COMMIT;
    p_status_msg := 'SUCESSO: Depósito efetuado com êxito.';[cite: 55]
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        p_status_msg := 'ERRO: Conta inexistente.';
        p_novo_saldo := NULL;
        ROLLBACK;[cite: 55]
    WHEN OTHERS THEN
        p_status_msg := 'ERRO INESPERADO: ' || SQLERRM;
        p_novo_saldo := NULL;
        ROLLBACK;[cite: 55]
END prc_realizar_deposito;
