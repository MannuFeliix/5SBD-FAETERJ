-- Exercício 2: Bloqueio Concorrente com FOR UPDATE[cite: 59]
/*
  RESPOSTA TÉCNICA (EXERCÍCIO 2):
  A cláusula SELECT ... FOR UPDATE aplica um bloqueio exclusivo em nível de linha
  (row-level lock) sobre o registro da conta de origem no instante da leitura
  do saldo, impedindo que outras transações simultâneas modifiquem ou leiam com
  bloqueio essa mesma conta até que o COMMIT ou ROLLBACK seja concluído[cite: 56, 60].
  Caso fosse omitida em um ambiente de alta concorrência, ocorreria uma condição
  de corrida (race condition / lost update): duas sessões paralelas poderiam ler
  o mesmo saldo inicial antes da atualização da outra, aprovando transferências
  simultâneas cuja soma ultrapassa o saldo real e deixando a conta negativa.
*/


-- Exercício 3: Manipulação de Parâmetros IN OUT (prc_sanitizar_texto)[cite: 59]
CREATE OR REPLACE PROCEDURE prc_sanitizar_texto (
    p_texto IN OUT VARCHAR2
) IS
BEGIN
    p_texto := UPPER(TRIM(p_texto));
END prc_sanitizar_texto;
/

