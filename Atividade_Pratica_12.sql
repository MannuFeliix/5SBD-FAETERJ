-- Exercício 1: Reajuste em massa de contas ativas
CREATE OR REPLACE PROCEDURE prc_reajustar_saldo_em_massa (
    p_percentual       IN  NUMBER,
    p_total_atualizado OUT NUMBER
) IS
BEGIN
    UPDATE tb_contas
    SET saldo = saldo * (1 + (p_percentual / 100))
    WHERE status = 'ATIVA';

    p_total_atualizado := SQL%ROWCOUNT;
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        p_total_atualizado := 0;
        ROLLBACK;
        RAISE;
END prc_reajustar_saldo_em_massa;
/[cite: 59]

DECLARE
    v_qtd_contas NUMBER;
BEGIN
    prc_reajustar_saldo_em_massa(
