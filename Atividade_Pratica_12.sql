-- ==========================================================
-- ETAPA 4: Procedure Transacional Completa (Transferência Bancária)
-- ==========================================================

CREATE OR REPLACE PROCEDURE prc_transferir_fundos (
    p_origem  IN NUMBER,
    p_destino IN NUMBER,
    p_valor   IN NUMBER
) IS
    v_saldo_origem       NUMBER;
    v_status_orig        VARCHAR2(10);
    v_status_dest        VARCHAR2(10);
    e_saldo_insuficiente EXCEPTION;
    e_conta_bloqueada    EXCEPTION;
BEGIN
    -- Validar valor[cite: 56]
    IF p_valor <= 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Valor de transferência inválido.');
    END IF;

    -- Bloquear e verificar conta de origem (SELECT FOR UPDATE evita concorrência)[cite: 56]
    SELECT saldo, status INTO v_saldo_origem, v_status_orig
    FROM tb_contas
    WHERE id_conta = p_origem
    FOR UPDATE;

    IF v_status_orig <> 'ATIVA' THEN
        RAISE e_conta_bloqueada;
    END IF;

    IF v_saldo_origem < p_valor THEN
        RAISE e_saldo_insuficiente;
    END IF;

    -- Verificar conta de destino[cite: 57]
    SELECT status INTO v_status_dest
    FROM tb_contas
    WHERE id_conta = p_destino;

    IF v_status_dest <> 'ATIVA' THEN
        RAISE e_conta_bloqueada;
    END IF;

    -- Debitar da conta de origem[cite: 57]
    UPDATE tb_contas SET saldo = saldo - p_valor WHERE id_conta = p_origem;

    -- Creditar na conta de destino[cite: 57]
    UPDATE tb_contas SET saldo = saldo + p_valor WHERE id_conta = p_destino;

    -- Registrar transação no extrato[cite: 57]
    INSERT INTO tb_movimentacoes (id_conta_origem, id_conta_dest, tipo_operacao, valor)
    VALUES (p_origem, p_destino, 'TRANSFERENCIA', p_valor);

    -- Confirmar transação atomicamente[cite: 57]
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Transferência de R$ ' || p_valor || ' concluída com sucesso.');
EXCEPTION
    WHEN e_saldo_insuficiente THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20002, 'Falha: Saldo insuficiente na conta de origem.');
    WHEN e_conta_bloqueada THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20003, 'Falha: Uma das contas envolvidas está bloqueada.');
    WHEN NO_DATA_FOUND THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20004, 'Falha: Conta de origem ou destino não localizada.');
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20099, 'Erro inesperado na transferência: ' || SQLERRM);
END prc_transferir_fundos;
/

