-- Exercício 1 (Seletividade e Leading Column)
SELECT nome, salario
FROM tb_funcionarios
WHERE cargo = 'ANALISTA';[cite: 28, 29]

/*
  RESPOSTA E ANÁLISE (EXERCÍCIO 1):
  O índice composto IDX_FUNC_DEP_CARGO_SAL foi criado na ordem
  (DEPARTAMENTO, CARGO, SALARIO). Pela regra da Leading Column (coluna líder),
  a estrutura B-Tree é ordenada primeiramente por DEPARTAMENTO[cite: 22, 27, 29].
  Como a consulta filtra apenas por CARGO = 'ANALISTA' (sem restringir
  DEPARTAMENTO), o Oracle não consegue fazer um INDEX RANGE SCAN direto e
  eficiente por cargo como faria se CARGO fosse a primeira coluna; além disso,
  a coluna NOME não está no índice, exigindo acesso à tabela para os registros
  correspondentes (podendo o otimizador optar por TABLE ACCESS FULL ou varredura
  do índice conforme o custo estimado)[cite: 22, 23, 28, 29].
*/


