-- ==========================================================
-- ETAPA 3: Aplicação de Índice B-Tree Único e Comparação de Custo
-- ==========================================================

-- 1. Criação do índice B-Tree Único
CREATE UNIQUE INDEX idx_func_matricula ON tb_funcionarios (matricula);[cite: 26]

-- 2. Reexecutar a consulta (analisar com Explain Plan no APEX)
SELECT id_funcionario, nome, departamento, salario
FROM tb_funcionarios
WHERE matricula = 'MAT-005420';[cite: 26]

/*
  SIMULAÇÃO DE RESULTADO / EXPLAIN PLAN (ETAPA 3):
  Index IDX_FUNC_MATRICULA created.

  Plano de Execução:
  - TABLE ACCESS BY INDEX ROWID BATCHED (TB_FUNCIONARIOS)
    - INDEX UNIQUE SCAN (IDX_FUNC_MATRICULA)
  Análise: O índice B-Tree localiza a chave em tempo O(log N) e obtém o ROWID
  para acessar diretamente o bloco da linha, reduzindo drasticamente o custo de E/S[cite: 21, 22, 26].
*/


-- ==========================================================
-- ETAPA 4: O Desafio do Function-Based Index (FBI)
-- ==========================================================

-- 1. Consulta aplicando função UPPER no nome (antes do FBI)
SELECT matricula, nome, cargo, salario
FROM tb_funcionarios
WHERE UPPER(nome) = 'FUNCIONARIO 2500';[cite: 27]

-- 2. Criação do Function-Based Index
CREATE INDEX idx_func_nome_upper ON tb_funcionarios (UPPER(nome));[cite: 27]

-- 3. Reavaliar a consulta (analisar com Explain Plan no APEX)
SELECT matricula, nome, cargo, salario
FROM tb_funcionarios
WHERE UPPER(nome) = 'FUNCIONARIO 2500';[cite: 27]

/*
  SIMULAÇÃO DE RESULTADO / EXPLAIN PLAN (ETAPA 4):
  - Antes do FBI: TABLE ACCESS FULL (a função UPPER impede uso de índice comum
    sobre a coluna pura)[cite: 22, 27].
  - Index IDX_FUNC_NOME_UPPER created.
  - Após o FBI: INDEX RANGE SCAN (ou TABLE ACCESS BY INDEX ROWID -> INDEX RANGE SCAN)
    utilizando IDX_FUNC_NOME_UPPER com o valor pré-computado em maiúsculo[cite: 22, 27].
*/


-- ==========================================================
-- ETAPA 5: Índice Composto e a Otimização de Cobertura (Index-Only Scan)
-- ==========================================================

-- 1. Criação de índice composto (departamento + cargo + salario)
CREATE INDEX idx_func_dep_cargo_sal ON tb_funcionarios (departamento, cargo, salario);[cite: 27]

-- 2. Consulta filtrando pela coluna líder (departamento) e retornando colunas do índice
SELECT cargo, salario
FROM tb_funcionarios
WHERE departamento = 'TI' AND cargo = 'ANALISTA';[cite: 27]

/*
  SIMULAÇÃO DE RESULTADO / EXPLAIN PLAN (ETAPA 5):
  Index IDX_FUNC_DEP_CARGO_SAL created.

  Plano de Execução:
  - INDEX RANGE SCAN (IDX_FUNC_DEP_CARGO_SAL)
  Análise: Como DEPARTAMENTO (leading column), CARGO e SALARIO estão todos na
  estrutura do índice, o Oracle resolve a consulta nos blocos folha do índice sem
  precisar acessar os blocos da tabela (Index-Only Scan)[cite: 22, 23, 27, 28].
*/


