-- Exercício 3: Trade-offs de Indexação em Todas as Colunas[cite: 24]
-- - Escrita (DML): cada INSERT, UPDATE ou DELETE atualiza todos os índices
--   associados, aumentando latência, REDO/UNDO e splits de blocos folha[cite: 18, 19, 25].
-- - Disco e Buffer Cache: ocupa mais armazenamento e disputa memória no Buffer
--   Cache com blocos de dados da tabela[cite: 25].
-- - CBO: o otimizador ignora índices de baixa seletividade em favor de Full Table
--   Scan, mantendo custo de manutenção sem ganho de leitura[cite: 15, 25].
