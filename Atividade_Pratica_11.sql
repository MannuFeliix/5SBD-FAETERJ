-- Exercício 1: Simulação de Ambiente Multi-Schema e Privilégios
/*
  RESPOSTA E FLUXO COMPLETO (EXERCÍCIO 1):
  Um sinônimo apenas abstrai o endereço/nome do objeto e NÃO concede privilégios
  de acesso[cite: 44]. Para que ANALISTA_BI consulte HR.EMPLOYEES via SELECT * FROM func;,
  são necessários dois passos[cite: 48]:

  -- Passo 1 (Executado por HR ou DBA): Conceder privilégio de leitura[cite: 48]
  GRANT SELECT ON hr.employees TO analista_bi;

  -- Passo 2 (Executado por ANALISTA_BI): Criar o sinônimo privado[cite: 48]
  CREATE SYNONYM func FOR hr.employees;

  -- Passo 3 (Consulta simplificada pelo ANALISTA_BI):[cite: 48]
  SELECT * FROM func;
*/


-- Exercício 2: Ordem de Resolução de Nomes
/*
  RESPOSTA E JUSTIFICATIVA (EXERCÍCIO 2):
  Ao executar SELECT * FROM pedidos;, o Oracle Database retornará os dados da
  TABELA FÍSICA PRÓPRIA (PEDIDOS) pertencente ao schema do usuário conectado[cite: 49].
  Justificativa: Na hierarquia de resolução de nomes não qualificados do Oracle,
  1º) Objetos locais do próprio schema têm prioridade máxima, seguidos por
  2º) Sinônimos privados do usuário e 3º) Sinônimos públicos (PUBLIC)[cite: 44, 49].
*/


-- Exercício 3: Sinônimos Inválidos / Órfãos
/*
  RESPOSTA E ANÁLISE (EXERCÍCIO 3):
  Quando o objeto base (ex.: tabela) é excluído com DROP TABLE, o sinônimo NÃO é
  removido automaticamente; ele permanece registrado no dicionário de dados como
  um sinônimo órfão/inválido[cite: 49]. Ao tentar consultá-lo posteriormente, o
  Oracle tenta resolver o apontamento e lança o erro:
  ORA-00942: table or view does not exist[cite: 44, 49].
*/
