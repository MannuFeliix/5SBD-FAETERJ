-- ==========================================================
-- ETAPA 2: Criação do Sinônimo Privado (Abstração Semântica)
-- ==========================================================

-- 1. Criar o Synonym privado apontando para a tabela complexa[cite: 45]
CREATE OR REPLACE SYNONYM clientes
FOR tb_cad_clientes_corp_nacional;

-- 2. Consultar os dados através do Synonym recém-criado[cite: 45, 46]
