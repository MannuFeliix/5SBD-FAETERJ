-- ==========================================================
-- ETAPA 4: Abstração de Sequences com Sinônimos
-- ==========================================================

-- 1. Criação de uma Sequence com nome técnico[cite: 47]
CREATE SEQUENCE seq_tb_cad_clientes_corp_id
START WITH 500
INCREMENT BY 1
NOCACHE;

-- 2. Criação de um Synonym para a Sequence[cite: 47]
CREATE OR REPLACE SYNONYM seq_clientes
FOR seq_tb_cad_clientes_corp_id;

-- 3. Consumir valores utilizando o Synonym[cite: 47]
SELECT seq_clientes.NEXTVAL AS proximo_id FROM DUAL;
SELECT seq_clientes.CURRVAL AS id_atual FROM DUAL;

/*
  SIMULAÇÃO DE RESULTADO (ETAPA 4):
  Sequence SEQ_TB_CAD_CLIENTES_CORP_ID created.
  Synonym SEQ_CLIENTES created.

  PROXIMO_ID
  ----------
  500

  ID_ATUAL
  --------
  500
*/


-- ==========================================================
-- ETAPA 5: O Poder da Refatoração Transparente (Substituição por View)
-- ==========================================================

-- 1. Criar uma View que expõe apenas clientes ativos com regras de negócio[cite: 47]
CREATE OR REPLACE VIEW vw_clientes_ativos AS
SELECT id_cliente, codigo_empresa, razao_social, cidade, limite_credito
FROM tb_cad_clientes_corp_nacional
WHERE status_conta = 'ATIVO';

-- 2. Redirecionar o Synonym existente para a View (sem parar a aplicação)[cite: 47]
CREATE OR REPLACE SYNONYM clientes
FOR vw_clientes_ativos;

-- 3. Executar exatamente a mesma consulta que a aplicação sempre executou[cite: 47]
SELECT * FROM clientes;

/*
  SIMULAÇÃO DE RESULTADO (ETAPA 5):
  View VW_CLIENTES_ATIVOS created.
  Synonym CLIENTES created.

